function fill(tpl: string, v: PersonaVars): string {
  const memory = v.memory.length ? v.memory.map((m) => `- ${m}`).join("\n") : "(아직 없음)";
  return tpl
    .replaceAll("{rival}", v.rival ? RIVAL : "")
    .replaceAll("{title}", v.title)
    .replaceAll("{city}", v.city)
    .replaceAll("{memory}", memory);
}

export function systemPrompt(chat: boolean, v: PersonaVars): string {
  return fill(chat ? CHAT : COMMAND, v);
}

